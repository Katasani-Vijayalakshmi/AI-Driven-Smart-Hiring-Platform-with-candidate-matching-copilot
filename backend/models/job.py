"""
backend/models/job.py
======================
Job posting dataclass and requirement profile schema.
Part of: AI Recruitment Copilot — Part 1
"""

from dataclasses import dataclass, field
from typing import List, Optional


@dataclass
class JobRequirement:
    """
    Structured job requirement profile extracted from a job description.
    Generated by: backend/job_analyzer.py
    """

    title:               str
    company:             Optional[str]  = None
    department:          Optional[str]  = None
    level:               Optional[str]  = None          # Junior / Mid / Senior / Lead
    employment_type:     str            = "Full-time"
    location:            Optional[str]  = None
    salary_range:        Optional[str]  = None

    # Extracted requirements
    required_skills:     List[str]      = field(default_factory=list)
    preferred_skills:    List[str]      = field(default_factory=list)
    nice_to_have:        List[str]      = field(default_factory=list)
    experience_required: float          = 0.0           # years
    education_required:  Optional[str]  = None          # e.g. "MS Computer Science"

    # Metadata
    raw_description:     Optional[str]  = None

    def all_required(self) -> List[str]:
        """Return combined must-have + preferred skills."""
        return list(set(self.required_skills + self.preferred_skills))

    def to_dict(self) -> dict:
        return {
            "title":               self.title,
            "company":             self.company,
            "level":               self.level,
            "required_skills":     ", ".join(self.required_skills),
            "preferred_skills":    ", ".join(self.preferred_skills),
            "experience_required": self.experience_required,
            "education_required":  self.education_required,
            "location":            self.location,
        }

    def __repr__(self) -> str:
        return (
            f"JobRequirement(title={self.title!r}, "
            f"required_skills={self.required_skills}, "
            f"experience={self.experience_required}yrs)"
        )
